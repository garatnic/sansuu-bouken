"""Build offline display readings. Dev dependency: sudachipy, sudachidict_core, pykakasi.
Runtime needs no API or tokenizer. IDs, masters, saves and original wording stay intact.
"""
import json,re,pathlib
from sudachipy import dictionary,tokenizer
from pykakasi import kakasi
root=pathlib.Path(__file__).resolve().parents[1]
kanji=re.compile(r'[\u3400-\u9fff\uf900-\ufaff々〆]')
japanese=re.compile(r'[\u3400-\u9fff\uf900-\ufaff々〆ぁ-ゖァ-ヺー]+')
sudachi=dictionary.Dictionary().tokenizer(); kak=kakasi()
def hira(s):return ''.join(chr(ord(c)-96) if 'ァ'<=c<='ヶ' else c for c in s)
# Game-specific readings and ambiguous single-character UI counters.
overrides={'遠見':'とおみ','問':'もん','体':'たい','人':'にん','品':'ひん','個':'こ','回':'かい','行':'ぎょう','列':'れつ','種':'しゅ','種類':'しゅるい','中':'ちゅう','大':'だい','小':'しょう','魔':'ま','氷':'こおり','金':'きん','銀':'ぎん','角':'つの','王':'おう','竜':'りゅう','龍':'りゅう','炎':'ほのお','着ぐるみ':'きぐるみ','一人':'ひとり','二人':'ふたり','一つ':'ひとつ','二つ':'ふたつ','一度':'いちど','今日':'きょう','明日':'あした','昨日':'きのう'}
lexical={'遠見':'とおみ','着ぐるみ':'きぐるみ','言う':'いう','木の実':'きのみ','鬼武':'おにむ','風晶鉱':'ふうしょうこう','銀露花':'ぎんろか','金青':'きんせい','雪光':'せっこう','青波':'あおなみ','青石':'あおいし','青瓦':'あおがわら','革職':'かわしょく','樹上':'じゅじょう','鋼':'はがね','首長':'くびなが','弓兵':'きゅうへい','黒鉄':'くろがね'}

lexical.update({'一歩':'いっぽ','七転び八起き':'ななころびやおき','一品':'いっぴん','四人':'よにん','大きな体':'おおきなからだ','森の中':'もりのなか','大神官':'だいしんかん','鍛冶師':'かじし','鉤刀':'こうとう','黄戦士':'きせんし','小竜':'しょうりゅう','双刀':'そうとう','炎角':'えんかく','紫晶':'ししょう','炎尾':'えんび','晶棘':'しょうきょく','骨帽子':'ほねぼうし','星界':'せいかい','深海真珠':'しんかいしんじゅ','角化石':'つのかせき','背板':'はいばん','鳥形':'とりがた','月紋':'げつもん','細剣':'さいけん','手斧':'ておの','森人':'もりびと','竜鱗':'りゅうりん','月角':'げっかく','竜翼':'りゅうよく','森精':'しんせい','ガラス杯':'ガラスはい','楓':'かえで','月相':'げっそう','月紋花形':'げつもんはながた','三重仕掛け':'さんじゅうじかけ','測量鎖':'そくりょうくさり','月銀':'げつぎん','虹葉草':'にじはそう','氷蜜の実':'ひょうみつのみ','虹羽蝶':'にじはちょう','晶トンボ':'しょうトンボ','尾羽':'おばね','風切羽':'かざきりばね','大角鹿':'おおつのじか','落角':'らっかく','渦紋':'うずもん','二枚貝':'にまいがい','青扇':'せいせん','白鹿角':'はくろっかく','晶洞':'しょうどう','双晶':'そうしょう','木偶':'でく','月香木':'げっこうぼく','帆船':'はんせん','火鳥':'かちょう','綿羽':'めんう','翼羽':'よくう','潮満ち':'しおみち','赤熱':'せきねつ','土精霊':'つちせいれい','天空峰':'てんくうほう','温泉谷':'おんせんだに','精霊の品':'せいれいのしな','青炎':'せいえん','竜皮':'りゅうひ','種標本':'たねひょうほん','炎書':'えんしょ','氷術師':'ひょうじゅつし','氷装':'ひょうそう','氷牢':'ひょうろう','氷梟':'ひょうきょう','氷精':'ひょうせい','氷霊獣':'ひょうれいじゅう','氷角獣':'ひょうかくじゅう','七王':'しちおう','剣盾':'けんじゅん','冥杖':'めいじょう','骨弓兵':'こつきゅうへい','重装骸兵':'じゅうそうがいへい'})

result={}; phrases=set(); sources=[]
for f in sorted(root.rglob('*')):
 rel=f.relative_to(root)
 if not f.is_file() or f.suffix not in ('.html','.js','.json','.css'):continue
 if rel.parts[0] in ('siyou','assets','tools','mocks'):continue
 if rel.parts[0]=='tests' and not (str(rel).startswith('tests/party-recommendation/integration/') or str(rel).startswith('tests/party-recommendation/mock/')):continue
 if f.name.startswith('hiragana'):continue
 sources.append(f)
 for phrase in japanese.findall(f.read_text()):
  if kanji.search(phrase):phrases.add(phrase)
def read(phrase):
 out=[]
 phrase=re.sub('|'.join(map(re.escape,sorted(lexical,key=len,reverse=True))),lambda m:lexical[m.group()],phrase)
 for token in sudachi.tokenize(phrase,tokenizer.Tokenizer.SplitMode.C):
  s=token.surface()
  if not kanji.search(s):out.append(s);continue
  r=lexical.get(s,hira(token.reading_form()))
  if kanji.search(r):r=''.join(t['hira'] if kanji.search(t['orig']) else t['orig'] for t in kak.convert(s))
  result.setdefault(s,r);out.append(r)
 return ''.join(out)
for phrase in sorted(phrases): result[phrase]=read(phrase)
# Cover fragments around numeric/template interpolation, and old saved encounter names.
for ch in sorted(set(''.join(kanji.findall(''.join(phrases))))):result.setdefault(ch,overrides.get(ch,read(ch)))
result.update(overrides);result.update(lexical)
# Greedy word readings cover most phrases; retain only contextual exceptions.
def convert(s,table):
 out='';i=0
 while i<len(s):
  match=next((s[i:j] for j in range(len(s),i,-1) if s[i:j] in table),None)
  if match:out+=table[match];i+=len(match)
  else:out+=s[i];i+=1
 return out
for key in sorted(list(result),key=len,reverse=True):
 if len(key)<2:continue
 value=result.pop(key)
 if convert(key,result)!=value:result[key]=value
assert all(not kanji.search(v) for v in result.values()),'Unresolved reading'
output='// Generated by tools/build-hiragana.py; reviewed overrides live in that file.\nwindow.BoukenHiraganaReadings='+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n'
(root/'common/hiragana-readings.js').write_text(output)
print(f'{len(sources)} sources, {len(phrases)} phrases, {len(result)} readings, {len(output.encode())} bytes')
